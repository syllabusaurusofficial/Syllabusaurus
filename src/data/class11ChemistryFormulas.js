function createFormula(chapterNumber, concept, name, expression, variables, options = {}) {
  const section = SECTIONS[chapterNumber];
  const chapter = concept;
  return {
    id: [BOARD, GRADE, SUBJECT, section, chapter, name]
      .map((value) => value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""))
      .join("-"),
    type: "formula",
    name,
    expression,
    board: BOARD,
    curriculum: "CBSE / NCERT",
    curriculumScope: "in_scope",
    grade: GRADE,
    subject: SUBJECT,
    chapter,
    section,
    chapterNumber,
    concept,
    variables,
    variableMeanings: variables,
    units: options.units || "Use consistent units; quantities are dimensionless where indicated.",
    conditions: options.conditions || "Apply to the stated chemical system and conditions.",
    importantNote: options.note || "",
    note: options.note || "",
    importance: options.importance || "high",
    category: options.category || "standard result",
    source: "NCERT",
    sourceReference: `NCERT Chemistry, Class XI, Chapter ${chapterNumber}; CBSE Class XI Chemistry curriculum.`,
    sourceUrl: NCERT_URL,
    verificationStatus: "VERIFIED",
    relatedFormulas: [],
    relatedConcepts: [],
    commonMistakes: [],
    examples: [],
    keywords: options.keywords || [],
  };
}

