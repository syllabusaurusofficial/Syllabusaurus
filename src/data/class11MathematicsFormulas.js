function slug(value) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function createFormula(chapterNumber, chapter, concept, name, expression, variables, options = {}) {
  const source = options.source || "NCERT";
  const chapterLabel = chapterNumber ? `Chapter ${chapterNumber}` : "Formative topic";
  const sourceSection = options.section?.replace(/^Formative-only content:\s*/i, "");
  return {
    id: [BOARD, GRADE, SUBJECT, chapter, name].map(slug).join("-"),
    type: "formula",
    name,
    expression,
    board: BOARD,
    curriculum: "CBSE / NCERT",
    curriculumScope: options.curriculumScope || "in_scope",
    grade: GRADE,
    subject: SUBJECT,
    chapter,
    chapterNumber,
    concept,
    variables,
    variableMeanings: variables,
    units: options.units || "Not applicable",
    conditions: options.conditions || "No additional restriction stated.",
    importance: options.importance || "medium",
    importantNote: options.importantNote || "",
    category: options.category || "standard result",
    source,
    sourceReference: options.sourceReference || (source === "NCERT"
      ? `${NCERT_REPRINT}, ${chapterLabel}${options.section ? `, ${options.section}` : ""}.`
      : `CBSE Mathematics syllabus for Class XI (2025–26), formative-only content${sourceSection ? `: ${sourceSection}` : ""}.`),
    sourceUrl: options.sourceUrl || (source === "NCERT"
      ? `https://ncert.nic.in/textbook/pdf/kemh1${String(chapterNumber).padStart(2, "0")}.pdf`
      : CBSE_SYLLABUS_URL),
    verificationStatus: options.verificationStatus || "verified",
    relatedFormulas: options.relatedFormulas || [],
    relatedConcepts: options.relatedConcepts || [],
    commonMistakes: options.commonMistakes || [],
    examples: [],
    keywords: options.keywords || [],
  };
}

