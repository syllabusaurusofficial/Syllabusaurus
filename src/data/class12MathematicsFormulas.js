function slug(value) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function formula(chapter, name, expression, variables = {}, conditions = "") {
  if (!CHAPTERS.includes(chapter)) {
    throw new Error(`Class XII Mathematics formula has an unknown chapter: ${chapter}.`);
  }
  return {
    id: [BOARD, GRADE, SUBJECT, chapter, name].map(slug).join("-"),
    type: "formula",
    name,
    expression,
    board: BOARD,
    curriculum: "CBSE / NCERT",
    curriculumScope: "in_scope",
    grade: GRADE,
    subject: SUBJECT,
    chapter,
    concept: chapter,
    variables,
    variableMeanings: variables,
    units: "Not applicable",
    conditions: conditions || "Use the stated domain and conditions.",
    importantNote: "",
    importance: "high",
    category: "standard result",
    source: "NCERT",
    sourceReference: `NCERT Mathematics, Class XII; CBSE Class XII Mathematics curriculum. ${chapter}.`,
    sourceUrl: "https://ncert.nic.in/textbook.php",
    verificationStatus: "verified",
    relatedFormulas: [],
    relatedConcepts: [],
    commonMistakes: [],
    examples: [],
    keywords: [],
  };
}

